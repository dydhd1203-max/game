'use strict';
// Hair template (stage 3 H5, 3단계-계획.txt 'hair' 7): the game's own reference figure (m short, f bob) in front,
// right and back, head, neck, the basic tee's collar and shoulders down to mid-chest, on white, as the first
// picture of a hairstyle art request (and of the bald base head request). Drawn by the runtime (?demo=1,
// nothing saved): idle, skin tone 0, hair colour 1 (갈색), bright face, basic outfit.
//   node tools/hair/make-hair-template.cjs [OUTDIR]      (default assets/hair-template, about 30 s)
// writes OUTDIR/머리-그림틀-<m|f>.png (1536 x 1024, three 512 x 1024 cells: front | right | back, no marks or text)
// and OUTDIR/머리-그림틀.json: per sex and view the head painting's transform from head-native units to template
// pixels ([a, b, c, d, e, f]: x = a u + c v + e, y = b u + d v + f), the figure size and the cut line, so a
// returned sheet maps back onto the head layers.
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..','..'),OUT=path.resolve(process.argv[2]||path.join(ROOT,'assets','hair-template'));
const L=require(ROOT+'/tools/foundation-garment-lib.cjs'),H=L.H;
const REF={m:'short',f:'bob'},VIEWS=['front','right','back'];
// front head at 14 px per head unit (head-frame.json m/f front pxPerUnit280 4.6759 at 280 px; the widest view, the
// f bob's back, then just fits a cell); every cell uses the same figure size, so the body, neck and collar match
const SIZE=Math.round(14*280/4.6759),CELL_W=512,CELL_H=1024,SHEET_W=1536,SHEET_H=1024;
const CUT=40.5;     // white from the front head unit v 40.5 down (mid-chest); the figure from its top to the cut centred
function headCtm(){return [...document.querySelectorAll('#fg-host .fg-cell')].map(cell=>{const svg=cell.querySelector('svg.qp-foundation-avatar');
  const view=[...svg.querySelectorAll('[data-foundation-head-view]')].find(v=>getComputedStyle(v).display!=='none'&&v.getBoundingClientRect().width>0)?.dataset.foundationHeadView||'front';
  const m=svg.querySelector('[data-foundation-head-paint="'+view+'"]').getScreenCTM();return[m.a,m.b,m.c,m.d,m.e+scrollX,m.f+scrollY];});}
(async()=>{
  fs.mkdirSync(OUT,{recursive:true});
  const tree=H.fsTree(ROOT),server=await H.serve(tree),browser=await H.launch({args:H.RASTER_ARGS}),rep={errors:[]};
  const meta={about:'Generated by tools/hair/make-hair-template.cjs; do not edit. ctm: head-native units -> template px.',size:SIZE,cell:[CELL_W,CELL_H],sheet:[SHEET_W,SHEET_H],cut:CUT,reference:REF,sexes:{}};
  try{
    const {page}=await L.openRuntime(browser,server.base,rep,{viewport:{width:SHEET_W+40,height:CELL_H+400}});await L.install(page,{});
    for(const sex of ['m','f']){
      const cells=VIEWS.map(direction=>({av:{sex,sk:0,hair:REF[sex]+':1',expression:'bright:0'},state:{action:'idle',direction,time:0,reducedMotion:true},size:SIZE}));
      // first draw: where the paint starts and the cut lies; second: that span centred in the cell
      let top=0,g,ctm,img,cutY;
      for(let pass=0;pass<2;pass++){
        g=await page.evaluate(spec=>__fg.grid(spec),{cells,cols:3,cellW:CELL_W,cellH:CELL_H+600,top,labelW:0,bg:'#ffffff'});ctm=await page.evaluate(headCtm);
        img=await L.capture(page,g);cutY=Math.round(ctm[0][3]*CUT+ctm[0][5]);
        let first=0;find:for(;first<cutY;first++)for(let x=0;x<Math.min(SHEET_W,img.width);x++){const i=(first*img.width+x)*4;if(img.data[i]<245||img.data[i+1]<245||img.data[i+2]<245)break find;}
        const edge=[...Array(cutY).keys()].some(y=>[0,CELL_W-1,CELL_W,2*CELL_W-1,2*CELL_W,3*CELL_W-1].some(x=>{const i=(y*img.width+x)*4;return img.data[i]<245;}));
        if(edge)throw Error(sex+': the figure touches a cell edge; lower SIZE');
        if(pass===0)top=Math.round(top+(CELL_H-(cutY-first))/2-first);
      }
      const png={width:SHEET_W,height:SHEET_H,data:Buffer.alloc(SHEET_W*SHEET_H*4,255)};
      for(let y=0;y<Math.min(SHEET_H,cutY,img.height);y++)img.data.copy(png.data,y*SHEET_W*4,y*img.width*4,y*img.width*4+Math.min(SHEET_W,img.width)*4);
      fs.writeFileSync(path.join(OUT,'머리-그림틀-'+sex+'.png'),H.png.encode(png));
      meta.sexes[sex]={style:REF[sex]+':1',cutY,views:Object.fromEntries(VIEWS.map((v,i)=>[v==='right'?'profile':v,{cell:g.rects[i],ctm:ctm[i].map(x=>+x.toFixed(4))}]))};
      console.log('머리-그림틀-'+sex+'.png: figure '+SIZE+' px, cut at y '+cutY);
    }
    fs.writeFileSync(path.join(OUT,'머리-그림틀.json'),JSON.stringify(meta,null,1)+'\n');
    if(rep.errors.length)throw Error(rep.errors.join('\n'));
  }finally{await browser.close();await server.close();}
})().catch(e=>{console.error(e);process.exit(1);});
