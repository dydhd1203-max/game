const {chromium}=require('playwright');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.QUIZ_BROWSER_EXECUTABLE||undefined});
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  await context.route('https://www.gstatic.com/firebasejs/**',r=>r.fulfill({body:'/* isolated preview adapter */',contentType:'text/javascript'}));
  const errors=[],checks=[],out=path.resolve(__dirname,'../검증');fs.mkdirSync(out,{recursive:true});
  const base='http://127.0.0.1:4173/?demo=1&session=verify-'+Date.now();
  const open=async query=>{const p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));await p.goto(base+query);await p.waitForFunction(()=>window.QPGame&&window.QPDemo&&window.QPAvatar?.atlas.ready===true&&window.QPClothes?.atlas.ready===true);return p;};
  // The old teacher-hosted live games (quiz/OX/team crossword) were removed on 2026-10-14;
  // QUIZQUIZ rooms are checked by their own tools. This keeps the shop/avatar flow.
  const a=await open('&user=하늘');
  await a.waitForFunction(()=>QPGame.getMe());
  const gold=p=>p.evaluate(()=>QPGame.getMe().gold);
  await a.evaluate(()=>QPGame.go('shop'));await a.locator('#shTabs [data-c="expression"]').click();
  const g=await gold(a);await a.locator('#shGrid [data-id="expression:happy:0"]').click();await a.locator('#btnBuy').click();
  await a.waitForFunction(()=>QPGame.getMe().owned['expression:happy:0']&&QPGame.getMe().av.expression==='happy:0');
  assert.equal(await gold(a),g-220);
  const first=await a.locator('#pvStage .qpx-body').evaluate(e=>e.getAnimations()[0].currentTime);
  await a.waitForTimeout(80);const second=await a.locator('#pvStage .qpx-body').evaluate(e=>e.getAnimations()[0].currentTime);assert(second>first);
  const times=await a.evaluate(()=>document.querySelector('#pvStage svg').getAnimations({subtree:true}).filter(x=>['qpx-body','qpx-hands','qpx-blink-half','qpx-blink-closed'].includes(x.animationName)).map(x=>({name:x.animationName,time:x.currentTime,iterations:x.effect.getTiming().iterations})));
  assert(times.length>=3&&times.every(t=>t.iterations===Infinity));
  checks.push('Paid face buying/equipping debits exact price; breathing and blink continue in fitting preview');
  await a.locator('#shTabs [data-c="hair"]').click();
  assert.equal(await a.locator('#shGrid [data-id]').count(),8);
  await a.locator('#shopOwned').click();
  assert(await a.locator('#shGrid [data-id="hair:bob:1"]').count());
  assert(await a.locator('#shGrid [data-id="hair:bob:5"]').count());
  const priorGender=await a.evaluate(()=>JSON.stringify({av:QPGame.getMe().av,owned:QPGame.getMe().owned,gold:QPGame.getMe().gold}));
  await a.locator('#btnGender').click();
  assert.equal(await a.locator('#avatarSexChoices .qp-pixel-avatar').count(),2);
  const genderSources=await a.locator('#avatarSexChoices image[data-qpx-sex]:not([data-qpx-tail])').evaluateAll(es=>es.map(e=>e.getAttribute('href')));
  assert.equal(genderSources.length,2);assert.notEqual(genderSources[0],genderSources[1]);
  await a.locator('#avatarSexChoices button[data-sex="m"]').click();
  await a.waitForFunction(()=>QPGame.getMe().av.sex==='m');
  const afterGender=await a.evaluate(()=>({av:QPGame.getMe().av,owned:QPGame.getMe().owned,gold:QPGame.getMe().gold}));
  const prior=JSON.parse(priorGender);assert.equal(afterGender.gold,prior.gold);assert.deepEqual(afterGender.owned,prior.owned);assert.deepEqual({...afterGender.av,sex:prior.av.sex,hair:prior.av.hair},prior.av);
  assert(['short','part','messy','spiky'].includes(afterGender.av.hair.split(':')[0]));
  checks.push('Male and female have different drawn heads; switching is free and preserves clothing, owned items and gold');
  await a.locator('#btnFace').click();await a.locator('#fSk button[data-i="4"]').click();
  assert.equal(await a.evaluate(()=>QPGame.getMe().av.sk),4);
  const skin=await a.locator('#pvStage .qpx-body [fill]').evaluateAll(es=>es.map(e=>e.getAttribute('fill')));
  assert(skin.includes(await a.evaluate(()=>PAL.skin[4][0])));
  checks.push('Separate male and female hair shops, owned hair colors together in wardrobe, skin changes body palette');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'검증결과.json'),JSON.stringify({checks,errors,viewport:'1440x900, one player page',motion:times},null,2));
  console.log(JSON.stringify({passed:checks,errors},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
