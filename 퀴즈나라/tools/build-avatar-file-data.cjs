/* Encode original artwork without resizing, recoloring or changing PNG bytes. */
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const sources = [
  'assets/sd-heads-female.png', 'assets/sd-heads-male.png',
  'assets/sd-heads-profile-female.png', 'assets/sd-heads-profile-male.png',
  'assets/sd-heads-back-female.png', 'assets/sd-heads-back-male.png',
  'assets/sd-tops.png', 'assets/sd-bottoms.png', 'assets/sd-hood.png',
  'assets/pixel-pets-v2.png', 'assets/sd-shoes.png', 'assets/sd-shoes-parts.png', 'assets/angel-effect.png'
];
const LIMIT = 25 * 1024 * 1024;
const bundles = [
  { sources, target: 'assets/avatar-file-data.js', global: 'QPAvatarFileData' },
  // Keep each static file below the Pages 25MiB limit. The old original
  // bundle stays byte-for-byte unchanged when new wardrobe art is added.
  // The reference body: its limbs and neck (and their rule-cleaned arms and
  // neck for pipeline garments). Garments have their own bundles below.
  { sources: ['assets/sd-foundation-ref-neck.png', 'assets/sd-foundation-ref-arms.png', 'assets/sd-foundation-ref-legs.png', 'assets/sd-foundation-ref-arms-clean.png', 'assets/sd-foundation-ref-neck-clean.png'], target: 'assets/avatar-file-data-foundation.js', global: 'QPAvatarFoundationFileData' },
  { sources: ['assets/sd-wardrobe-wave.png'], target: 'assets/avatar-file-data-wardrobe.js', global: 'QPAvatarWardrobeFileData' },
  { sources: ['assets/sd-clothes-male.png'], target: 'assets/avatar-file-data-male.js', global: 'QPAvatarMaleFileData' }
];
// One bundle per garment record (stage 3), listed by the generated garment
// index (assets/sd-garments-index.js: records[id].files {m, f, bundle}). Each
// adds its atlas keys to the one shared registry QPAvatarGarmentFileData,
// never replacing it, so any number of bundles can load in any order
// (avatar-image.js resolves a bundle once its own key is present).
const GARMENT_REGISTRY = 'QPAvatarGarmentFileData', GARMENT_BUNDLE = /^assets\/avatar-file-data-garment-[a-z]+-[a-z0-9_]+\.js$/;
function garmentIndex() {
  const file = path.join(root, 'assets/sd-garments-index.js'), sandbox = {};
  new (require('node:vm').Script)(fs.readFileSync(file, 'utf8'), { filename: file }).runInNewContext({ window: sandbox, globalThis: sandbox });
  assert(sandbox.QPFoundationGarmentIndex, 'assets/sd-garments-index.js did not define QPFoundationGarmentIndex');
  return sandbox.QPFoundationGarmentIndex;
}
function garmentBundles() {
  const out = [];
  for (const [id, entry] of Object.entries(garmentIndex().records).sort(([a], [b]) => a < b ? -1 : 1)) {
    const files = entry.files;assert(GARMENT_BUNDLE.test(files.bundle), id + ': bundle name ' + files.bundle);
    out.push({ id, sources: entry.sexes.map(sex => files[sex]), target: files.bundle, registry: GARMENT_REGISTRY });
  }
  return out;
}
function encode(entry) {
  const data = Object.fromEntries(entry.sources.map(file => [file, 'data:image/png;base64,' + fs.readFileSync(path.join(root, file)).toString('base64')]));
  if (entry.registry) return '/* Generated by tools/build-avatar-file-data.cjs from original PNG bytes (garment ' + entry.id + ').\n' +
    '   Loaded only when index.html is opened as a local file. Do not edit. Adds its keys to\n' +
    '   window.' + entry.registry + ' (one registry for every garment bundle). */\n' +
    '(function(root){\'use strict\';const data=root.' + entry.registry + '||(root.' + entry.registry + '=Object.create(null)),add=' + JSON.stringify(data) + ';\n' +
    'for(const key of Object.keys(add))if(!(key in data))Object.defineProperty(data,key,{value:add[key],enumerable:true});})(window);\n';
  return '/* Generated by tools/build-avatar-file-data.cjs from original PNG bytes.\n' +
    '   Loaded only when index.html is opened as a local file. Do not edit. */\n' +
    'window.' + entry.global + ' = Object.freeze(' + JSON.stringify(data) + ');\n';
}
function build(check = false) {
  const all = [...bundles, ...garmentBundles()];
  for (const entry of all) {
    const output = encode(entry), target = path.join(root, entry.target);
    assert(Buffer.byteLength(output) <= LIMIT, 'Local avatar bundle exceeds Pages file limit: ' + entry.target);
    if (check) assert.equal(fs.existsSync(target) && fs.readFileSync(target, 'utf8') === output, true,
      'Local avatar data is stale. Run node tools/build-avatar-file-data.cjs');
    else fs.writeFileSync(target, output);
    console.log(entry.target + ' ' + (check ? 'matches' : 'encodes') + ' ' + entry.sources.length + ' original PNG files');
  }
  // A garment bundle left behind by a removed or renamed record.
  const wanted = new Set(all.map(e => e.target));
  for (const name of fs.readdirSync(path.join(root, 'assets')).filter(n => n.startsWith('avatar-file-data-garment-'))) {
    const rel = 'assets/' + name;
    if (check) assert(wanted.has(rel), 'Stale garment bundle (no index record): ' + rel + '. Run node tools/build-avatar-file-data.cjs');
    else if (!wanted.has(rel)) { fs.rmSync(path.join(root, rel)); console.log(rel + ' removed (no index record)'); }
  }
  return all;
}
module.exports = build;
module.exports.garmentBundles = garmentBundles;
if (require.main === module) build(process.argv.includes('--check'));
