/* Encode original artwork without resizing, recoloring or changing PNG bytes. */
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const sources = [
  'assets/sd-heads-female.png', 'assets/sd-heads-male.png',
  'assets/sd-heads-profile-female.png', 'assets/sd-heads-profile-male.png',
  'assets/sd-heads-back-female.png', 'assets/sd-heads-back-male.png',
  'assets/sd-tops.png', 'assets/sd-bottoms.png', 'assets/sd-hood.png',
  'assets/pixel-pets-v2.png', 'assets/sd-shoes.png', 'assets/sd-shoes-parts.png', 'assets/angel-effect.png'
];
const bundles = [
  { sources, target: 'assets/avatar-file-data.js', global: 'QPAvatarFileData' },
  // Keep each static file below the Pages 25MiB limit. The old original
  // bundle stays byte-for-byte unchanged when new wardrobe art is added.
  { sources: ['assets/sd-foundation-neck.png','assets/sd-foundation-skin.png', 'assets/sd-foundation-basic.png', 'assets/sd-foundation-shirt-profile.png', 'assets/sd-foundation-sleeves.png', 'assets/sd-foundation-torso.png', 'assets/sd-foundation-sleeves-raised.png'], target: 'assets/avatar-file-data-foundation.js', global: 'QPAvatarFoundationFileData' },
  { sources: ['assets/sd-wardrobe-wave.png'], target: 'assets/avatar-file-data-wardrobe.js', global: 'QPAvatarWardrobeFileData' },
  { sources: ['assets/sd-clothes-male.png'], target: 'assets/avatar-file-data-male.js', global: 'QPAvatarMaleFileData' }
];
function build(check = false) {
  for (const entry of bundles) {
    const data = Object.fromEntries(entry.sources.map(file => [file, 'data:image/png;base64,' + fs.readFileSync(path.join(root, file)).toString('base64')]));
    const output = '/* Generated by tools/build-avatar-file-data.cjs from original PNG bytes.\n' +
      '   Loaded only when index.html is opened as a local file. Do not edit. */\n' +
      'window.' + entry.global + ' = Object.freeze(' + JSON.stringify(data) + ');\n';
    const target = path.join(root, entry.target);
    assert(Buffer.byteLength(output) <= 25 * 1024 * 1024, 'Local avatar bundle exceeds Pages file limit: ' + entry.target);
    if (check) assert.equal(fs.readFileSync(target, 'utf8') === output, true,
      'Local avatar data is stale. Run node tools/build-avatar-file-data.cjs');
    else fs.writeFileSync(target, output);
    console.log(entry.target + ' ' + (check ? 'matches' : 'encodes') + ' ' + entry.sources.length + ' original PNG files');
  }
}
module.exports = build;
if (require.main === module) build(process.argv.includes('--check'));
